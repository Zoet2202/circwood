"""Filesystem paths for the Circwood WP4 project.

All paths are anchored to the repository root (three levels up from this file:
``src/circwood/config.py`` -> repo root) so the package behaves identically no
matter what the current working directory is.
"""

from __future__ import annotations

from pathlib import Path

# .../repo/src/circwood/config.py -> parents[2] == repo root
ROOT_DIR = Path(__file__).resolve().parents[2]

CONFIG_DIR = ROOT_DIR / "config"
SSB_QUERY_DIR = CONFIG_DIR / "ssb_queries"
NODES_FILE = CONFIG_DIR / "nodes.json"

# Researcher-editable carbon model (open in Excel as CSV).
CARBON_DENSITIES_FILE = CONFIG_DIR / "carbon_densities.csv"
CARBON_NODES_FILE = CONFIG_DIR / "carbon_nodes.csv"

DATA_DIR = ROOT_DIR / "data"
RAW_DIR = DATA_DIR / "raw"
PROCESSED_DIR = DATA_DIR / "processed"

# Verbatim SSB API responses, one file per table, written before parsing so a
# failed run can still be debugged offline and two pulls can be diffed. A cache,
# not an input: git-ignored and regenerated by every fresh run.
RAW_SSB_DIR = RAW_DIR / "ssb"

# Generated pipeline outputs.
SANKEY_CSV = PROCESSED_DIR / "sankey_data.csv"
CARBON_CSV = PROCESSED_DIR / "carbon_data.csv"
# Empirical HWP fraction beta(year, species) for the external rotation model
# (Phase F, written by ``circwood.analysis.hwp.export_beta_series``).
BETA_SERIES_CSV = PROCESSED_DIR / "beta_series.csv"

# The public static site (Phase D). ``site/`` is committed source; ``site/data``
# is generated output (git-ignored) — the bundle is derived from the committed
# CSVs at build/deploy time rather than committed twice.
SITE_DIR = ROOT_DIR / "site"
SITE_DATA_DIR = SITE_DIR / "data"
BUNDLE_JSON = SITE_DATA_DIR / "circwood.json"

# Raw source inputs used by the fresh (API) pipeline.
TREINDUSTRIEN_CSV = RAW_DIR / "treindustrien_production_data.csv"
FAO_CSV = RAW_DIR / "FAO_Data.csv"

# Harvest by county (SSB 03795, agg_KommFylker backcast codelist) — the data
# behind the `region` dimension. Committed, like the Treindustrien CSV: the
# cached pipeline reads it; a fresh run regenerates it from the 03795_fylke
# query. If absent, the dataset simply stays national (region == "NO").
HARVEST_FYLKE_CSV = RAW_DIR / "harvest_by_fylke.csv"

# Exports by partner country (SSB 08799, the by-country sibling of 08801) —
# the data behind the `destination` dimension. Same contract as the county
# file: committed, read by the cached pipeline, regenerated by a fresh run from
# the 08799_* chunk queries. If absent, every row stays destination="domestic".
EXPORTS_PARTNER_CSV = RAW_DIR / "exports_by_partner.csv"

# ISO 3166-1 alpha-2 partner code -> English display label for the site, taken
# from SSB's own `Land` codelist (lang=en). A lookup, not a closed map: a code
# without a label is shown as the code, never refused.
DESTINATION_LABELS_FILE = CONFIG_DIR / "destination_labels.csv"

__all__ = [
    "ROOT_DIR",
    "CONFIG_DIR",
    "SSB_QUERY_DIR",
    "NODES_FILE",
    "CARBON_DENSITIES_FILE",
    "CARBON_NODES_FILE",
    "DATA_DIR",
    "RAW_DIR",
    "RAW_SSB_DIR",
    "PROCESSED_DIR",
    "SANKEY_CSV",
    "CARBON_CSV",
    "BETA_SERIES_CSV",
    "SITE_DIR",
    "SITE_DATA_DIR",
    "BUNDLE_JSON",
    "TREINDUSTRIEN_CSV",
    "FAO_CSV",
    "HARVEST_FYLKE_CSV",
    "EXPORTS_PARTNER_CSV",
    "DESTINATION_LABELS_FILE",
]
